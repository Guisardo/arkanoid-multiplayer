// Sprite loading for real CC0 assets (spec §13). Node-guarded like
// gameFont.ts: in node tests there is no DOM/fetch, so lookups resolve to
// null and painters fall back to procedural geometry. In the browser the Pixi
// Assets cache serves textures loaded once at boot via AssetPack manifest.
//
// Frame resolution (ADR 0004): the AssetPack manifest declares the atlas *frame
// table* (`atlas-<hash>.png.json`), not one asset per frame, and Pixi's JSON
// loader just parses it — it does not build textures. So the frame table is
// read here, its image is loaded as a single texture, and each frame is cut
// out as a sub-texture sharing that image's source. One GPU texture, N frames:
// exactly what ParticleContainer needs.
import { Assets, Rectangle, Texture } from "pixi.js";
import type { TextureOptions } from "pixi.js";
import { assetUrl } from "./assetUrl";

/** Sprite descriptor paths — now using atlas frame names (AssetPack manifest). */
export const SPRITE_PATHS = {
  paddles: {
    red: "paddle-a-red.png",
    purple: "paddle-b-purple.png",
    blue: "paddle-c-blue.png",
  },
  balls: {
    red: "ball-red.png",
    yellow: "ball-yellow.png",
    green: "ball-green.png",
  },
  backgrounds: {
    pixelSpace: "pixel-space.png",
  },
  /**
   * Particle frames (ADR 0009): 8 grayscale 16x16 shapes, tinted per effect
   * preset at emit time. Generated by scripts/gen-particle-frames.mjs.
   */
  particles: {
    circle: "particle-circle.png",
    square: "particle-square.png",
    triangle: "particle-triangle.png",
    star: "particle-star.png",
    streak: "particle-streak.png",
    debris: "particle-debris.png",
    splat: "particle-splat.png",
    ring: "particle-ring.png",
  },
} as const;

/** Every frame name the game looks up, in one list. */
const ALL_FRAMES: readonly string[] = [
  ...Object.values(SPRITE_PATHS.paddles),
  ...Object.values(SPRITE_PATHS.balls),
  ...Object.values(SPRITE_PATHS.backgrounds),
  ...Object.values(SPRITE_PATHS.particles),
];

/** Alias AssetPack gives the packed atlas bundle. */
const ATLAS_ALIAS = "atlas";

/**
 * Bundle names (ADR 0004, ticket 87).
 *
 * #86 packed every frame into ONE atlas under a single `default` bundle, and
 * that has to stay: frames cut from one image share a `TextureSource`, which
 * is what lets `ParticleContainer` batch the whole effect layer in a single
 * draw call. Splitting the atlas per bundle would give each bundle its own
 * source and blow that budget. (Verified: re-tagging the source folder to
 * `{gameplay}` stops the texture packer running at all and unbundles every
 * frame into its own asset — the opposite of what we want.)
 *
 * So the split here is about *when* a bundle is requested, not what it holds.
 * `boot` is what the landing/menu draws; `gameplay` is deferred until a match
 * is created, so first paint does not wait on game textures.
 *
 * `default` is what the shipped manifest actually declares, so it is the
 * fallback: a checkout that has not re-run `npm run assetpack` still boots
 * with art instead of degrading to procedural geometry.
 */
const BOOT_BUNDLE = "boot";
const GAMEPLAY_BUNDLE = "gameplay";
const LEGACY_BUNDLE = "default";

/**
 * Test-only reset for ALL per-page module state: the gameplay-bundle
 * bookkeeping, the memoised `Assets.init`, the frame cache and the last error.
 *
 * Exported alongside the loader rather than through `import.meta` so the intent
 * stays explicit. All of it persists across calls by design — that is what
 * makes "initialises exactly once" and "never clears the frame cache on reload"
 * true in the browser — but it also means every test file has to clear it
 * between cases or the first test's cached atlas answers for all the rest.
 */
export const gameplayAssetsLoaded = {
  reset(): void {
    gameplayLoaded = false;
    gameplayInFlight = null;
    assetsInitPromise = null;
    loaded.clear();
    atlasResolved = false;
    lastError = null;
  },
};

/** True once the gameplay bundle has loaded successfully this page. */
let gameplayLoaded = false;

/**
 * The in-flight gameplay load, so concurrent callers (a rematch racing a
 * first start, say) share one fetch instead of racing to start several.
 */
let gameplayInFlight: Promise<void> | null = null;

/**
 * Load a named bundle, falling back to the single-bundle manifest.
 *
 * The fallback is keyed on the OUTCOME, not on an exception: Pixi's
 * `loadBundle` does not reject for a bundle the manifest does not declare. It
 * logs "Asset id atlas was not found in the Cache" and resolves, so a
 * try/catch fallback never fires and the atlas silently stays unresolved. So
 * request the preferred name, then check whether the atlas actually arrived;
 * only if it did not, try the legacy name.
 */
async function loadBundleTolerant(name: string): Promise<void> {
  await Assets.loadBundle(name);
  if (pickAtlasTable(Assets.get(ATLAS_ALIAS)) !== null) return;
  // The preferred bundle is absent (the committed manifest declares only
  // `default`), so ask for that instead.
  await Assets.loadBundle(LEGACY_BUNDLE);
}

/**
 * Load the gameplay bundle, if it is not already loaded.
 *
 * Call this at match creation, not at boot. Never throws: a missing gameplay
 * bundle degrades to procedural geometry so a match can still start, which is
 * the same contract `initAssets` has.
 */
export async function ensureGameplayAssets(): Promise<void> {
  if (gameplayLoaded) return;
  // Share the in-flight load. A caller arriving mid-load must not start a
  // second fetch of the same bytes.
  if (gameplayInFlight) return gameplayInFlight;

  gameplayInFlight = (async () => {
    try {
      await initAssetsPipeline();
      await loadBundleTolerant(GAMEPLAY_BUNDLE);
      await registerAtlasFrames();
      // Only a bundle that ACTUALLY produced frames counts as loaded. Pixi
      // resolves `loadBundle` for a name the manifest does not declare, so
      // reaching this point does not prove the atlas arrived — and marking it
      // loaded anyway would pin the session to procedural geometry with no
      // retry, so a later match could never pick art back up after a
      // transient network failure.
      if (atlasResolved) {
        gameplayLoaded = true;
        lastError = null;
      } else {
        lastError = new Error(`[spriteSheet] ${GAMEPLAY_BUNDLE} bundle produced no atlas frames`);
      }
    } catch (err) {
      // Deliberately does NOT set gameplayLoaded: a transient network failure
      // should not permanently pin the game to procedural art for the session.
      lastError = err;
      console.warn(`[spriteSheet] ${GAMEPLAY_BUNDLE} bundle failed; using procedural art`, err);
    } finally {
      gameplayInFlight = null;
    }
  })();

  return gameplayInFlight;
}

/**
 * AssetPack's `output` is `public/assets`, so everything it emits sits under
 * `assets/` in the served tree. Both the manifest URL *and* Pixi's `basePath`
 * need that prefix: the manifest's own `src` entries are bare filenames, so
 * without a base path they resolve against the site root and 404 into the SPA's
 * index.html — which parses as "no assets" and silently drops the whole game
 * to procedural geometry.
 */
function assetsUrl(name: string): string {
  return assetUrl(`assets/${name}`);
}

interface AtlasFrameJson {
  frame: { x: number; y: number; w: number; h: number };
  rotated: boolean;
  trimmed: boolean;
  spriteSourceSize: { x: number; y: number; w: number; h: number };
  sourceSize: { w: number; h: number };
}

interface AtlasJson {
  frames: Record<string, AtlasFrameJson>;
  meta: { image: string };
}

const loaded = new Map<string, Texture>();

/** Cache a loaded texture by frame name (called by the loader, not painters). */
export function rememberTexture(path: string, texture: Texture): void {
  loaded.set(path, texture);
}

/**
 * Look up a loaded texture. Null when unavailable (node tests, load failure,
 * or not yet loaded) — painters must fall back to procedural geometry.
 */
export function spriteTexture(path: string): Texture | null {
  if (typeof document === "undefined") return null;
  return loaded.get(path) ?? null;
}

/**
 * Why the last `initAssets` failed, or null. Exposed so a silently-degraded
 * boot is diagnosable — a swallowed error here once hid a bad manifest URL for
 * an entire release.
 */
let lastError: unknown = null;

/** Whether the `atlas` alias resolved to a usable frame table. */
let atlasResolved = false;

/** The failure from the last `initAssets()`, or null if it succeeded. */
export function spriteLoadError(): unknown {
  return lastError;
}

/**
 * Initialize Pixi Assets with the AssetPack manifest and cut every frame out
 * of the packed atlas. Called once at app startup (src/app/main.ts).
 *
 * Never throws: a missing manifest or a failed fetch degrades to procedural
 * geometry, which is always readable. It does warn — a silent fallback here is
 * indistinguishable from "we shipped procedural art on purpose".
 */
export async function initAssets(): Promise<void> {
  if (typeof document === "undefined") return;
  lastError = null;
  atlasResolved = false;
  try {
    await initAssetsPipeline();
    await loadBundleTolerant(BOOT_BUNDLE);
    await registerAtlasFrames();
  } catch (err) {
    // Missing manifest/bundle must never break the game — geometry fallback covers it.
    lastError = err;
    console.warn("[spriteSheet] atlas load failed; using procedural art", err);
  }
}

/**
 * Point Pixi at the manifest, exactly once per page.
 *
 * AssetPack's `output` is `public/assets`, so the manifest's own `src` entries
 * are bare filenames and need a matching `basePath` (see `assetsUrl`).
 *
 * `Assets.init` is NOT idempotent: calling it twice logs "AssetManager already
 * initialized" and, worse, leaves the cache unpopulated — so a second caller's
 * `loadBundle` then resolves nothing and the atlas silently vanishes. Both
 * `initAssets` and `ensureGameplayAssets` need the pipeline, and they run
 * concurrently at match start, so the init is memoised and shared here.
 *
 * A FAILED init is deliberately NOT memoised: caching the rejection would pin
 * the page to procedural geometry for the rest of the session after one
 * transient network failure, with no way to retry.
 */
let assetsInitPromise: Promise<void> | null = null;

async function initAssetsPipeline(): Promise<void> {
  assetsInitPromise ??= Assets.init({
    manifest: assetsUrl("manifest.json"),
    basePath: assetsUrl(""),
  });
  try {
    await assetsInitPromise;
  } catch (err) {
    // Drop the memo so a later caller can try again rather than replaying the
    // same rejection forever.
    assetsInitPromise = null;
    throw err;
  }
}

/** Cut the atlas frames into the module-level texture cache. */
async function registerAtlasFrames(): Promise<void> {
  const atlas = pickAtlasTable(Assets.get(ATLAS_ALIAS));
  if (atlas === null) return;
  await registerFrames(atlas);
  atlasResolved = loaded.size > 0;
}

/**
 * Pick the frame table out of whatever the `atlas` alias resolved to.
 *
 * AssetPack declares one asset with *two* srcs (the PNG and WebP frame
 * tables), so Pixi resolves the alias to an array. Each element is normally a
 * `Spritesheet` — Pixi's own atlas parser turns the frame table into one base
 * texture plus per-frame sub-textures. A manifest that resolves to plain JSON
 * is also accepted and cut by hand. Returns null when nothing usable came back.
 */
function pickAtlasTable(resolved: unknown): AtlasSpritesheet | AtlasJson | null {
  const candidates: unknown[] = Array.isArray(resolved) ? resolved : [resolved];
  for (const candidate of candidates) {
    if (isSpritesheet(candidate)) return candidate;
    if (isAtlasTable(candidate)) return candidate;
  }
  return null;
}

/** A Pixi `Spritesheet`: a base texture plus named frame sub-textures. */
interface AtlasSpritesheet {
  textures: Record<string, Texture>;
}

function isSpritesheet(value: unknown): value is AtlasSpritesheet {
  if (typeof value !== "object" || value === null) return false;
  const textures = (value as { textures?: unknown }).textures;
  return typeof textures === "object" && textures !== null;
}

function isAtlasTable(value: unknown): value is AtlasJson {
  if (typeof value !== "object" || value === null) return false;
  const frames = (value as { frames?: unknown }).frames;
  return typeof frames === "object" && frames !== null;
}

/**
 * Register every frame the game looks up.
 *
 * Either path ends with all frames sharing one `TextureSource` — that shared
 * source is what lets `ParticleContainer` batch a whole field of particles into
 * a single draw call.
 */
async function registerFrames(atlas: AtlasSpritesheet | AtlasJson): Promise<void> {
  if (isSpritesheet(atlas)) {
    for (const name of ALL_FRAMES) {
      const texture = atlas.textures[name];
      if (texture !== undefined) loaded.set(name, texture);
    }
    return;
  }
  await cutRawAtlas(atlas);
}

/** Manual frame-cutting, for a manifest that resolves to a bare frame table. */
async function cutRawAtlas(atlas: AtlasJson): Promise<void> {
  const frames = atlas.frames;
  const image = atlas.meta.image;
  if (typeof image !== "string" || image.length === 0) return;

  const alias = `atlas-image:${image}`;
  Assets.add({ alias, src: assetsUrl(image) });
  const base = await Assets.load<Texture>(alias);
  const source = base.source;

  for (const name of ALL_FRAMES) {
    const frame = frames[name];
    if (frame === undefined) continue;
    // The packer runs with allowRotation: false, so frames are axis-aligned.
    // A rotated frame would need UV swapping — skip rather than render garbage.
    if (frame.rotated) continue;
    const opts: TextureOptions = {
      source,
      frame: new Rectangle(frame.frame.x, frame.frame.y, frame.frame.w, frame.frame.h),
      orig: new Rectangle(0, 0, frame.sourceSize.w, frame.sourceSize.h),
      label: name,
    };
    if (frame.trimmed) {
      opts.trim = new Rectangle(
        frame.spriteSourceSize.x,
        frame.spriteSourceSize.y,
        frame.spriteSourceSize.w,
        frame.spriteSourceSize.h,
      );
    }
    loaded.set(name, new Texture(opts));
  }
}

/** Shape of the `spriteDebugState()` probe, for typed e2e consumers. */
export interface SpriteSheetDebug {
  error: unknown;
  atlasResolved: boolean;
  frames: readonly string[];
}

/**
 * Test/e2e probe: what the `atlas` alias resolved to, and which frames were
 * cut. A silently-degraded boot is otherwise indistinguishable from one where
 * procedural art is the intended look.
 */
export function spriteDebugState(): SpriteSheetDebug {
  return { error: lastError, atlasResolved, frames: [...loaded.keys()] };
}

/** Preload every shipped sprite once at boot; failures degrade to geometry. */
export async function loadSkinSprites(): Promise<void> {
  // Kept for backward compatibility — now delegates to initAssets
  await initAssets();
}
